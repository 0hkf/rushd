-- Explicit PostgreSQL baseline for an empty application database, targeting public.
-- Review, back up, and test against an isolated database before applying manually.
-- Not an upgrade: refuses any existing application table/relation in a non-system schema.
-- No accounts, application data, database/schema creation, or permissions are seeded.
-- For psql, use ON_ERROR_STOP=1 so any failure stops the script immediately.
-- The transaction ensures a failed check or DDL statement leaves no partial baseline.
-- Existing 20261006-* files remain separate upgrade paths; do not run the auth upgrade
-- after this baseline, since its tables and constraints are already included here.

BEGIN;
SET LOCAL search_path = pg_catalog, public;

DO $baseline_guard$
DECLARE
    existing_relations text;
BEGIN
    SELECT string_agg(format('%I.%I', namespace.nspname, relation.relname), ', '
                      ORDER BY namespace.nspname, relation.relname)
      INTO existing_relations
      FROM pg_catalog.pg_class relation
      JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
     WHERE relation.relname IN ('users', 'properties', 'auth_sessions', 'refresh_tokens')
       AND relation.relkind IN ('r', 'p', 'v', 'm', 'f')
       AND namespace.nspname <> 'information_schema'
       AND left(namespace.nspname, 3) <> 'pg_';

    IF existing_relations IS NOT NULL THEN
        RAISE EXCEPTION 'Empty-database baseline refused; existing application relations: %', existing_relations
            USING ERRCODE = '42P07';
    END IF;
END;
$baseline_guard$;

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT uq_users_email UNIQUE (email),
    -- SELLER is retained solely for compatibility with the existing Java enum.
    CONSTRAINT ck_users_role CHECK (role IN ('BUYER', 'SELLER', 'ADMIN'))
);

CREATE TABLE public.properties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Keep the legacy physical column; the Java relation is named publisher.
    seller_id bigint NOT NULL,
    title varchar(255) NOT NULL,
    type varchar(255) NOT NULL,
    listing_type varchar(10) NOT NULL DEFAULT 'SALE',
    rental_period varchar(10),
    city varchar(255) NOT NULL,
    district varchar(255) NOT NULL,
    google_place_id varchar(255),
    formatted_address varchar(500),
    neighborhood varchar(150),
    latitude numeric(10,7),
    longitude numeric(10,7),
    area numeric(12,2) NOT NULL,
    price numeric(19,2) NOT NULL,
    street_width numeric(10,2),
    facade varchar(255),
    purpose varchar(255),
    description text,
    status varchar(255) NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT fk_properties_publisher FOREIGN KEY (seller_id) REFERENCES public.users(id),
    CONSTRAINT ck_properties_type CHECK (type IN (
        'LAND', 'APARTMENT', 'VILLA', 'BUILDING', 'COMMERCIAL', 'FARM', 'OTHER'
    )),
    CONSTRAINT ck_properties_facade CHECK (facade IN (
        'NORTH', 'SOUTH', 'EAST', 'WEST', 'NORTHEAST', 'NORTHWEST',
        'SOUTHEAST', 'SOUTHWEST', 'MULTIPLE', 'UNKNOWN'
    )),
    CONSTRAINT ck_properties_purpose CHECK (purpose IN (
        'RESIDENTIAL', 'COMMERCIAL', 'INVESTMENT', 'AGRICULTURAL', 'MIXED', 'OTHER'
    )),
    CONSTRAINT ck_properties_status CHECK (status IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'SOLD')),
    CONSTRAINT ck_property_rental_pricing CHECK (
        (listing_type = 'SALE' AND rental_period IS NULL) OR
        (listing_type = 'RENT' AND rental_period IS NOT NULL AND rental_period IN ('MONTHLY', 'YEARLY'))
    ),
    CONSTRAINT ck_property_coordinates CHECK (
        (latitude IS NULL OR latitude BETWEEN -90 AND 90) AND
        (longitude IS NULL OR longitude BETWEEN -180 AND 180)
    )
);

CREATE INDEX idx_properties_seller_id ON public.properties(seller_id);
CREATE INDEX idx_properties_status ON public.properties(status);
CREATE INDEX idx_properties_city ON public.properties(city);
CREATE INDEX idx_properties_district ON public.properties(district);
CREATE INDEX idx_properties_google_place_id ON public.properties(google_place_id);

CREATE TABLE public.auth_sessions (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    revoked_at timestamp(6) with time zone,
    CONSTRAINT fk_auth_sessions_user FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE INDEX idx_auth_session_user ON public.auth_sessions(user_id);

CREATE TABLE public.refresh_tokens (
    id uuid PRIMARY KEY,
    session_id uuid NOT NULL,
    token_hash varchar(64) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    consumed_at timestamp(6) with time zone,
    replaced_by_token_id uuid,
    CONSTRAINT fk_refresh_tokens_session FOREIGN KEY (session_id) REFERENCES public.auth_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_replacement FOREIGN KEY (replaced_by_token_id) REFERENCES public.refresh_tokens(id),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_consumption CHECK (
        (consumed_at IS NULL AND replaced_by_token_id IS NULL) OR
        (consumed_at IS NOT NULL AND replaced_by_token_id IS NOT NULL)
    )
);

CREATE INDEX idx_refresh_family ON public.refresh_tokens(session_id);
CREATE INDEX idx_refresh_expiry ON public.refresh_tokens(expires_at);

COMMIT;
